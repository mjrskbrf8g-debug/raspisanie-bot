def parse_ru_date(s: str, year: int = YEAR) -> str:
    """Превращает 'дд.мм' или 'д.мм' в 'ГГГГ-ММ-ДД'."""
    day_str, month_str = s.strip().split(".")
    d = date(year, int(month_str), int(day_str))
    return d.isoformat()
